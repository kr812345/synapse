import os
from pptx import Presentation
from pptx.util import Inches, Pt
from tools.tool_registry import ToolInterface
import uuid

class PPTTool(ToolInterface):
    name = "ppt_generator"
    description = "Generates a PowerPoint (PPTX) presentation from provided slides."
    parameters = {
        "title": "string",
        "slides": "list of dicts containing 'title' and 'content'",
        "filename": "string (optional)"
    }
    required_permissions = ["file_system_write"]

    async def execute(self, title: str = "Presentation", slides: list = None, filename: str = "", **kwargs) -> dict:
        try:
            if slides is None:
                slides = [{"title": "Welcome", "content": "Welcome to the presentation."}]

            prs = Presentation()

            # Title Slide
            title_slide_layout = prs.slide_layouts[0]
            slide = prs.slides.add_slide(title_slide_layout)
            slide.shapes.title.text = title
            slide.placeholders[1].text = "Generated by Synapse AI"

            # Content Slides
            bullet_slide_layout = prs.slide_layouts[1]
            for slide_data in slides:
                slide = prs.slides.add_slide(bullet_slide_layout)
                shapes = slide.shapes
                
                title_shape = shapes.title
                body_shape = shapes.placeholders[1]
                
                title_shape.text = slide_data.get("title", "Slide")
                
                tf = body_shape.text_frame
                tf.text = slide_data.get("content", "")

            output_dir = os.path.join(os.getcwd(), "artifacts")
            os.makedirs(output_dir, exist_ok=True)
            
            if not filename:
                filename = f"presentation_{uuid.uuid4().hex[:8]}.pptx"
            if not filename.endswith(".pptx"):
                filename += ".pptx"
                
            file_path = os.path.join(output_dir, filename)
            prs.save(file_path)
            
            return {
                "status": "success", 
                "message": f"PowerPoint presentation successfully generated.",
                "file_path": file_path
            }
        except Exception as e:
            return {"status": "error", "message": str(e)}
